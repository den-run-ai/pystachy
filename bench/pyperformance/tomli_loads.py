"""
Benchmark ``loads()`` function of the ``tomli`` module
on a large TOML file of GitHub's real world data generated by
the ``generate_data.py`` script.

It heavily exercises string operations such as concatenation,
subscripting and iteration.

Author: Kumar Aditya
"""

import time  # Pystachy port: time.perf_counter() is pyperf.perf_counter(); pyperf is not imported
# Pystachy port: the standard library's tomllib stands in for tomli, whose code it has been
# since Python 3.11; tomli itself is not vendored.
import tomllib as tomli

TIMED: list[float] = []  # Pystachy port: the seconds of each timed part


# Pystachy port: a document of the upstream fixture's shape, 1,000 pull requests of
# GitHub's API as TOML: an array of tables with nested tables and arrays of tables, whose
# values are mostly strings (URLs, escapes), with integers, booleans and arrays. The 16.8 MB
# fixture holds other people's names and text and is not vendored; these values are made up.
def user_lines(lines: list[str], table: str, number: int) -> None:
    login = "user%d" % (number % 97)
    lines.append(table)
    lines.append('login = "%s"' % login)
    lines.append("id = %d" % (number * 7919 % 10000019))
    lines.append('node_id = "MDQ6VXNlcj%08d"' % (number * 104729 % 100000000))
    lines.append('avatar_url = "https://avatars.example.org/u/%d?v=4"' % (number * 7919 % 10000019))
    lines.append('gravatar_id = ""')
    for key, path in [("url", ""), ("followers_url", "/followers"), ("following_url", "/following{/other_user}"),
                      ("gists_url", "/gists{/gist_id}"), ("starred_url", "/starred{/owner}{/repo}"),
                      ("subscriptions_url", "/subscriptions"), ("organizations_url", "/orgs"),
                      ("repos_url", "/repos"), ("events_url", "/events{/privacy}"),
                      ("received_events_url", "/received_events")]:
        lines.append('%s = "https://api.example.org/users/%s%s"' % (key, login, path))
    lines.append('html_url = "https://example.org/%s"' % login)
    lines.append('type = "User"')
    lines.append("site_admin = %s" % ("true" if number % 11 == 0 else "false"))


def repo_lines(lines: list[str], table: str, number: int) -> None:
    owner = "user%d" % (number % 97)
    lines.append(table)
    lines.append("id = %d" % (81613525 + number))
    lines.append('node_id = "MDEwOlJlcG9zaXRvcnk%09d"' % (number * 15485863 % 1000000000))
    lines.append('name = "project"')
    lines.append('full_name = "%s/project"' % owner)
    lines.append("private = false")
    lines.append('description = "The \\"project\\" repository:\\tfork %d"' % number)
    lines.append("fork = %s" % ("true" if number % 2 == 1 else "false"))
    for key in ["url", "forks_url", "keys_url", "hooks_url", "issues_url", "pulls_url", "tags_url", "commits_url"]:
        lines.append('%s = "https://api.example.org/repos/%s/project/%s{/id}"' % (key, owner, key[:-4]))
    lines.append('created_at = "2017-02-10T%02d:%02d:%02dZ"' % (number % 24, number % 60, number * 7 % 60))
    lines.append("size = %d" % (431000 + number * 13))
    lines.append("stargazers_count = %d" % (number % 500))
    lines.append("watchers = %d" % (number % 500))
    lines.append('language = "Python"')
    lines.append("has_issues = %s" % ("true" if number % 3 == 0 else "false"))
    lines.append("archived = false")
    lines.append('topics = ["topic%d", "topic%d", "shared"]' % (number % 5, number % 7))
    lines.append('default_branch = "main"')


def synthetic_document(records: int) -> str:
    lines: list[str] = []
    for i in range(records):
        number = 93214 - i
        lines.append("[[data]]")
        lines.append('url = "https://api.example.org/repos/python/project/pulls/%d"' % number)
        lines.append("id = %d" % (946803344 - 7919 * i))
        lines.append('node_id = "PR_kwDOBN0Z8c%08d"' % (i * 15485863 % 100000000))
        lines.append('html_url = "https://example.org/python/project/pull/%d"' % number)
        lines.append("number = %d" % number)
        lines.append('state = "%s"' % ("open" if i % 3 == 0 else "closed"))
        lines.append("locked = %s" % ("true" if i % 13 == 0 else "false"))
        lines.append('title = "[3.%d] gh-%d: Fix item %d for a \\"quoted\\" encoding"' % (9 + i % 4, number - 1290, i))
        lines.append('body = "Fix item %d.\\r\\n\\r\\nA second paragraph with a tab\\tand \\u00e9.\\r\\n"' % i)
        lines.append('created_at = "2022-05-25T%02d:%02d:%02dZ"' % (i % 24, i % 60, i * 7 % 60))
        lines.append('merge_commit_sha = "%040d"' % (i * 1000003))
        lines.append("draft = %s" % ("true" if i % 17 == 0 else "false"))
        lines.append('author_association = "MEMBER"')
        lines.append("")
        for reviewer in range(i % 3):
            user_lines(lines, "[[data.requested_reviewers]]", i * 3 + reviewer)
            lines.append("")
        for label in range(i % 4):
            lines.append("[[data.labels]]")
            lines.append("id = %d" % (666979871 + label))
            lines.append('url = "https://api.example.org/repos/python/project/labels/awaiting%%20review%%20%d"' % label)
            lines.append('name = "awaiting review %d"' % label)
            lines.append('color = "fbca%02d"' % label)
            lines.append("default = false")
            lines.append("")
        user_lines(lines, "[data.user]", i)
        lines.append("[data.head]")
        lines.append('label = "user%d:backport-%d"' % (i % 97, i))
        lines.append('ref = "backport-%d"' % i)
        lines.append('sha = "%040d"' % (i * 999983))
        lines.append("[data.base]")
        lines.append('label = "python:3.%d"' % (9 + i % 4))
        lines.append('ref = "3.%d"' % (9 + i % 4))
        lines.append('sha = "%040d"' % (i * 999979))
        user_lines(lines, "[data.head.user]", i)
        repo_lines(lines, "[data.head.repo]", i)
        user_lines(lines, "[data.base.user]", 0)
        repo_lines(lines, "[data.base.repo]", 0)
        for link in ["self", "html", "issue", "comments", "review_comments", "review_comment", "commits", "statuses"]:
            lines.append("[data._links.%s]" % link)
            lines.append('href = "https://api.example.org/repos/python/project/pulls/%d/%s"' % (number, link))
        user_lines(lines, "[data.head.repo.owner]", i)
        lines.append("[data.head.repo.license]")
        lines.append('key = "other"')
        lines.append('name = "Other"')
        lines.append('spdx_id = "NOASSERTION"')
    return "\n".join(lines) + "\n"


# Pystachy port: the document is a parameter, where upstream reads its fixture beside
# __file__; the main generates one or reads the file it is given.
def bench_tomli_loads(loops: int, data: str):
    range_it = range(loops)
    t0 = time.perf_counter()  # Pystachy port: time.perf_counter() is pyperf.perf_counter()
    for _ in range_it:
        tomli.loads(data)
    TIMED.append(time.perf_counter() - t0)  # Pystachy port: the seconds, which upstream returns

if __name__ == "__main__":
    # Pystachy port: a deterministic main replaces pyperf.Runner: argv[1] is the
    # number of loops, argv[2] the number of generated records and argv[3], if given,
    # a TOML file to parse instead (upstream's data/tomli-bench-data.toml, for one). The
    # parsed records are counted and summed outside the timer, and the time goes to stderr.
    import hashlib
    import sys
    loops = int(sys.argv[1]) if len(sys.argv) > 1 else 1
    records = int(sys.argv[2]) if len(sys.argv) > 2 else 200
    if len(sys.argv) > 3:
        with open(sys.argv[3], encoding="utf-8") as fixture:
            text = fixture.read()
    else:
        text = synthetic_document(records)
    bench_tomli_loads(loops, text)
    print("seconds", sum(TIMED), file=sys.stderr)
    pulls = tomli.loads(text)["data"]
    ids = 0
    reviewers = 0
    labels = 0
    for pull in pulls:
        ids += pull["id"] + pull["number"]
        if "requested_reviewers" in pull:
            reviewers += len(pull["requested_reviewers"])
        if "labels" in pull:
            labels += len(pull["labels"])
    last = pulls[len(pulls) - 1]
    print("tomli_loads", loops, len(text), hashlib.md5(text.encode("utf-8")).hexdigest(), len(pulls), ids, reviewers, labels)
    print(last["title"], last["user"]["login"], last["head"]["repo"]["full_name"], last["_links"]["self"]["href"],
          last["locked"], last["head"]["repo"]["topics"])
