"""Interleaved scalar-literal backend screen, with CPython output witnesses.

Run from any directory; compiler roots must stay unchanged until completion.
Runtime preparation is measured separately. The backend deliberately separates
Clang's O2 IR optimization from code generation so their costs remain visible;
it is a frozen-IR replay, not the ordinary driver's combined command or a
complete-bootstrap benchmark. No timing threshold determines pass/fail.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import signal
import statistics
import subprocess
import sys
import time
from pathlib import Path


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def source_identity(root):
    # Include every compiler/runtime source and bundled library, including files
    # absent from Git. Generated bytecode/build output is not a source input.
    paths = [root / name for name in ("pystachy.py", "runtime.py", "runtime.c", "pyext.c", "pyembed.c")]
    for name in ("src", "lib", "ryu", "mpz"):
        paths.extend(p for p in (root / name).rglob("*")
                     if p.is_file() and "__pycache__" not in p.parts and p.suffix not in (".pyc", ".pyo"))
    files = {str(p.relative_to(root)): digest(p) for p in sorted(set(paths))}
    commit = subprocess.run(["git", "-C", str(root), "rev-parse", "HEAD"], capture_output=True, text=True, check=False)
    return {"root": str(root), "commit": commit.stdout.strip() if commit.returncode == 0 else None,
            "files": files, "sha256": hashlib.sha256(json.dumps(files, sort_keys=True).encode()).hexdigest()}


def measure(command, directory, env, log, timeout):
    log.parent.mkdir(parents=True, exist_ok=True)
    before = os.getloadavg()
    start = time.perf_counter()
    timed_out = False
    with log.with_suffix(".stdout").open("wb") as out, log.with_suffix(".stderr").open("wb") as err:
        proc = subprocess.Popen([str(a) for a in command], cwd=directory, env=env,
                                stdout=out, stderr=err, start_new_session=True)
        def expired(signum, frame):
            raise TimeoutError("command exceeded its time limit")
        previous = signal.signal(signal.SIGALRM, expired)
        signal.setitimer(signal.ITIMER_REAL, timeout)
        try:
            _, status, usage = os.wait4(proc.pid, 0)
        except TimeoutError:
            timed_out = True
            os.killpg(proc.pid, signal.SIGKILL)
            _, status, usage = os.wait4(proc.pid, 0)
        except BaseException:
            os.killpg(proc.pid, signal.SIGKILL)
            os.wait4(proc.pid, 0)
            raise
        finally:
            signal.setitimer(signal.ITIMER_REAL, 0)
            signal.signal(signal.SIGALRM, previous)
        proc.returncode = os.waitstatus_to_exitcode(status)
    row = {"command": [str(a) for a in command], "cwd": str(directory),
           "wall_s": time.perf_counter() - start, "cpu_s": usage.ru_utime + usage.ru_stime,
           "wait4_max_rss_kib": usage.ru_maxrss, "exit_code": proc.returncode, "timed_out": timed_out,
           "load_before": before, "load_after": os.getloadavg(),
           "stdout_sha256": digest(log.with_suffix(".stdout")),
           "stderr_sha256": digest(log.with_suffix(".stderr"))}
    if proc.returncode:
        raise RuntimeError(json.dumps(row) + "\n" + log.with_suffix(".stderr").read_text(errors="replace")[-4000:])
    return row


def source(shape, n, consumer):
    item_type = "tuple[int, int]" if shape == "tuple" else shape
    items = [str(j - n // 2) if shape == "int" else repr((j - n // 2) * .125) if shape == "float" else
             ("True" if j % 3 else "False") if shape == "bool" else f"({j}, {j % 31})" for j in range(n)]
    last = "values[-1][0]" if shape == "tuple" else "int(values[-1])" if shape in ("bool", "float") else "values[-1]"
    literal = "[" + ", ".join(items) + "]"
    prefix = "import sys\n\ndef make_values() -> list[" + item_type + "]:\n    return " + literal + "\n\n"
    if consumer == "local":
        # This private list never escapes; ordinary inlining may expose its
        # contents and remove stores/loads. A noinline copy helper can lose that.
        prefix += "def local() -> int:\n    values = " + literal + "\n    return len(values) + " + last + "\n\n"
        loop = "        checksum += local()\n"
    else:
        # Keep actual fresh lists reachable in a global bounded batch. The other
        # consumer deliberately omits this escape so the tradeoff stays visible.
        prefix += "held: list[list[" + item_type + "]] = []\n\n"
        loop = ("        values = make_values()\n        held.append(values)\n"
                "        checksum += len(values) + " + last + "\n"
                "        if len(held) == 32:\n            held.clear()\n")
    return (prefix + "def repeat(count: int) -> int:\n    checksum = 0\n    for _ in range(count):\n" +
            loop + "    return checksum\n\nprint(make_values())\nprint(repeat(int(sys.argv[1])))\n")


def ir_stats(path):
    ir = path.read_text()
    return {"bytes": path.stat().st_size, "sha256": digest(path),
            "instruction_lines": sum(bool(re.match(r"^  [^ ;}]", line)) for line in ir.splitlines()),
            "append_calls": len(re.findall(r"\bcall void @pys_list_append\(", ir)),
            "constant_list_calls": len(re.findall(r"\bcall ptr @pys_list_from_const\(", ir))}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--baseline", type=Path, required=True)
    parser.add_argument("--candidate", type=Path, required=True)
    parser.add_argument("--python", type=Path, default=Path(sys.executable))
    parser.add_argument("--llvm", type=Path, required=True)
    parser.add_argument("--work", type=Path, required=True)
    parser.add_argument("--report", type=Path, required=True)
    parser.add_argument("--shapes", default="int,float,bool")
    parser.add_argument("--sizes", default="31,32,4096")
    parser.add_argument("--consumers", default="escape,local")
    parser.add_argument("--inline-control", action="store_true", help="also remove only the candidate helper's noinline attribute before O2")
    parser.add_argument("--samples", type=int, default=3)
    parser.add_argument("--execution-samples", type=int, default=5)
    parser.add_argument("--repetitions", type=int, default=5000)
    parser.add_argument("--minimum-elements", type=int, default=20000000,
                        help="scale small-list repetitions so startup does not dominate the hot constructor control")
    parser.add_argument("--timeout", type=float, default=180)
    parser.add_argument("--cpus", help="comma-separated affinity, applied to all child processes")
    args = parser.parse_args()
    roots = {"baseline": args.baseline.resolve(), "candidate": args.candidate.resolve()}
    if args.inline_control:
        roots["candidate-inline"] = args.candidate.resolve()
    args.python, args.llvm, args.work = args.python.absolute(), args.llvm.resolve(), args.work.resolve()
    shapes, sizes = args.shapes.split(","), [int(v) for v in args.sizes.split(",")]
    consumers = args.consumers.split(",")
    if set(shapes) - {"int", "float", "bool", "tuple"} or set(consumers) - {"escape", "local"} or min(sizes) < 1 or min(args.samples, args.execution_samples, args.repetitions) < 1:
        parser.error("positive sizes/sample counts/repetitions and int,float,bool,tuple shapes required")
    if args.work.exists():
        parser.error("work directory must be new")
    args.work.mkdir(parents=True)
    if args.cpus:
        os.sched_setaffinity(0, {int(v) for v in args.cpus.split(",")})
    env = {k: v for k, v in os.environ.items() if not k.startswith("PYSTACHY_") and k not in ("PYTHONPATH", "PYTHONHOME")}
    env.update(PYSTACHY_LLVM=str(args.llvm), PYSTACHY_JOBS="1")
    report = {"schema_version": 1, "complete": False, "python": str(args.python),
              "python_realpath": str(args.python.resolve()), "python_sha256": digest(args.python),
              "python_version": subprocess.check_output([args.python, "-c", "import sys; print(sys.version)"], text=True, timeout=args.timeout).strip(),
              "frontend_host": "CPython running each frozen checkout's current pystachy.py; no native compiler binary is used",
              "affinity": sorted(os.sched_getaffinity(0)), "host": dict(zip(("sysname", "nodename", "release", "version", "machine"), os.uname())),
              "note": "Clang O2 optimization and codegen are separate replay commands. Runtime preparation is excluded. RSS is wait4 per-command maximum, not aggregate process-tree RSS.",
              "source_before": {label: source_identity(root) for label, root in roots.items()},
              "harness_sha256": digest(__file__), "tools": {}, "preparation": {}, "inputs": {},
              "frontend": {}, "backend": [], "execution": []}
    args.report.parent.mkdir(parents=True, exist_ok=True)

    def save():
        args.report.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n")

    try:
        for name in ("clang", "opt", "llvm-link", "llvm-dis", "llvm-size"):
            tool = args.llvm / name
            report["tools"][name] = {"path": str(tool), "sha256": digest(tool),
                                      "version": subprocess.check_output([tool, "--version"], text=True, timeout=args.timeout)}
        runtime = {}
        for label, root in roots.items():
            directory = args.work / label
            directory.mkdir()
            if label == "candidate-inline":
                runtime[label] = runtime["candidate"]
                report["preparation"][label] = {"reuses": "candidate", "runtime_sha256": digest(runtime[label])}
                continue
            tiny = directory / "tiny.py"
            tiny.write_text("print(7)\n")
            cache_env = dict(env, PYSTACHY_HOME=str(root), PYSTACHY_CACHE=str(directory / "cache"))
            report["preparation"][label] = measure([args.python, root / "pystachy.py", "build", tiny, "-o", directory / "tiny"], root, cache_env, directory / "preparation", args.timeout)
            cached = list((directory / "cache").glob("runtime-py-*.bc"))
            if len(cached) != 1:
                raise RuntimeError(f"expected one prepared runtime, found {cached}")
            runtime[label] = cached[0]
            report["preparation"][label]["runtime_sha256"] = digest(cached[0])
            witness = subprocess.run([directory / "tiny"], env=env, timeout=args.timeout, capture_output=True, check=True)
            if witness.stdout != b"7\n" or witness.stderr:
                raise RuntimeError("runtime preparation witness differs from CPython")
            save()
        for shape, consumer in ((shape, consumer) for shape in shapes for consumer in consumers):
            for n in sizes:
                key = f"{shape}-{consumer}-{n}"
                repetitions = max(args.repetitions, (args.minimum_elements + n - 1) // n)
                program = args.work / (key + ".py")
                program.write_text(source(shape, n, consumer))
                expected = subprocess.run([args.python, program, str(repetitions)], env=env, timeout=args.timeout, capture_output=True, check=True)
                if expected.stderr:
                    raise RuntimeError("CPython control unexpectedly wrote stderr")
                oracle = expected.stdout
                report["inputs"][key] = {"sha256": digest(program), "source_bytes": program.stat().st_size,
                                          "oracle_sha256": hashlib.sha256(oracle).hexdigest(),
                                          "oracle_stderr_sha256": hashlib.sha256(expected.stderr).hexdigest(), "repetitions": repetitions}
                for label, root in roots.items():
                    directory = args.work / label / key
                    directory.mkdir()
                    raw = directory / "raw.ll"
                    row = measure([args.python, root / "pystachy.py", "ir", program, "-o", raw], root,
                                  dict(env, PYSTACHY_HOME=str(root)), directory / "frontend", args.timeout)
                    row["raw_ir"] = ir_stats(raw)
                    report["frontend"][label + "/" + key] = row
                    if label == "candidate-inline" and raw.read_bytes() != (args.work / "candidate" / key / "raw.ll").read_bytes():
                        raise RuntimeError("inline policy controls must use identical candidate raw IR")
                    text = raw.read_text()
                    if "declare ptr @pys_new(" in text:
                        raise RuntimeError("screen requires the ordinary no-late-allocator AOT path")
                    (directory / "program.ll").write_text(text + "\n@pys_plain = constant i64 1\n")
                binaries = {}
                for sample in range(args.samples):
                    labels = list(roots)
                    order = labels[sample % len(labels):] + labels[:sample % len(labels)]
                    for label in order:
                        directory = args.work / label / key
                        stem = directory / f"sample-{sample}"
                        linked, optimized, obj, binary = [stem.with_suffix(s) for s in (".bc", ".opt.bc", ".o", ".exe")]
                        phases = {}
                        program_ir = args.work / ("candidate" if label == "candidate-inline" else label) / key / "program.ll"
                        commands = {
                            "llvm_link": [args.llvm / "llvm-link", "--only-needed", program_ir, runtime[label], "-o", linked],
                            "optimize": [args.llvm / "clang", "-O2", "-c", "-emit-llvm", linked, "-o", optimized],
                            "codegen": [args.llvm / "clang", "-O2", "-c", "-Xclang", "-disable-llvm-passes", "-mllvm", "-time-passes", optimized, "-o", obj],
                            "native_link": [args.llvm / "clang", obj, "-o", binary, "-lm"],
                        }
                        linked_before_policy_sha256 = ""
                        for phase, command in commands.items():
                            if phase == "optimize":
                                linked_before_policy_sha256 = digest(linked)
                                if label == "candidate-inline":
                                    control = [args.llvm / "opt", "-passes=forceattrs", "-force-remove-attribute=pys_list_from_const:noinline", linked, "-o", linked]
                                    phases["inline_control"] = measure(control, roots[label], env, directory / f"sample-{sample}-inline-control", args.timeout)
                            phases[phase] = measure(command, roots[label], env, directory / f"sample-{sample}-{phase}", args.timeout)
                        optimized_ir = stem.with_suffix(".optimized.ll")
                        subprocess.run([args.llvm / "llvm-dis", optimized, "-o", optimized_ir], check=True, capture_output=True, timeout=args.timeout)
                        witness = subprocess.run([binary, str(repetitions)], env=env, timeout=args.timeout, capture_output=True, check=True)
                        if witness.stdout != oracle or witness.stderr != expected.stderr:
                            raise RuntimeError(f"{label}/{key}/{sample} output differs from CPython")
                        sections = subprocess.check_output([args.llvm / "llvm-size", "--format=sysv", obj], text=True, timeout=args.timeout)
                        section_bytes = {m[1]: int(m[2]) for m in re.finditer(r"^(\.[^\s]+)\s+([0-9]+)\s+", sections, re.MULTILINE)}
                        profile = (directory / f"sample-{sample}-codegen").with_suffix(".stderr").read_text()
                        row = {"label": label, "input": key, "sample": sample, "phases": phases,
                               "wall_s": sum(v["wall_s"] for k, v in phases.items() if k != "inline_control"),
                               "cpu_s": sum(v["cpu_s"] for k, v in phases.items() if k != "inline_control"),
                               "max_phase_rss_kib": max(v["wait4_max_rss_kib"] for k, v in phases.items() if k != "inline_control"),
                               "optimized_ir": ir_stats(optimized_ir), "object_bytes": obj.stat().st_size,
                               "binary_bytes": binary.stat().st_size, "binary_sha256": digest(binary), "oracle_passed": True,
                               "witness_stdout_sha256": hashlib.sha256(witness.stdout).hexdigest(),
                               "witness_stderr_sha256": hashlib.sha256(witness.stderr).hexdigest(),
                               "linked_before_policy_sha256": linked_before_policy_sha256,
                               "object_sections": section_bytes,
                               "text_bytes": sum(v for k, v in section_bytes.items() if k.startswith(".text")),
                               "codegen_profile": [line.strip() for line in profile.splitlines()
                                                   if "Instruction Selection" in line or "Register Allocator" in line]}
                        report["backend"].append(row)
                        binaries[label] = binary
                        print(json.dumps({k: row[k] for k in ("label", "input", "sample", "wall_s", "max_phase_rss_kib", "binary_bytes")}), flush=True)
                        save()
                for sample in range(args.execution_samples):
                    labels = list(roots)
                    order = labels[sample % len(labels):] + labels[:sample % len(labels)]
                    for label in order:
                        log = args.work / label / key / f"execution-{sample}"
                        row = measure([binaries[label], str(repetitions)], roots[label], env, log, args.timeout)
                        if log.with_suffix(".stdout").read_bytes() != oracle or log.with_suffix(".stderr").read_bytes() != expected.stderr:
                            raise RuntimeError("timed execution output differs from CPython")
                        report["execution"].append(dict(row, label=label, input=key, sample=sample, oracle_passed=True))
                save()
        if args.inline_control:
            report["inline_control_identical_linked_inputs"] = all(
                len({r["linked_before_policy_sha256"] for r in report["backend"]
                     if r["input"] == key and r["label"] in ("candidate", "candidate-inline")}) == 1
                for key in report["inputs"])
            if not report["inline_control_identical_linked_inputs"]:
                raise RuntimeError("inline policy variants did not use identical linked bitcode")
        report["source_after"] = {label: source_identity(root) for label, root in roots.items()}
        report["source_unchanged"] = all(report["source_before"][label] == report["source_after"][label] for label in roots)
        if not report["source_unchanged"]:
            raise RuntimeError("compiler source changed during the experiment")
        report["summary"] = {}
        for label in roots:
            for key in report["inputs"]:
                builds = [r for r in report["backend"] if r["label"] == label and r["input"] == key]
                runs = [r for r in report["execution"] if r["label"] == label and r["input"] == key]
                report["summary"][label + "/" + key] = {
                    "backend_median_s": statistics.median(r["wall_s"] for r in builds),
                    "backend_range_s": [min(r["wall_s"] for r in builds), max(r["wall_s"] for r in builds)],
                    "backend_cpu_median_s": statistics.median(r["cpu_s"] for r in builds),
                    "execution_median_s": statistics.median(r["wall_s"] for r in runs),
                    "execution_cpu_median_s": statistics.median(r["cpu_s"] for r in runs),
                    "execution_range_s": [min(r["wall_s"] for r in runs), max(r["wall_s"] for r in runs)]}
        report["complete"] = True
    except Exception as error:
        report["error"] = str(error)
        raise
    finally:
        save()


if __name__ == "__main__":
    main()
