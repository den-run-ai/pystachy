#!/usr/bin/env python3
"""Embed exact prepared JSON documents for the separate in-memory GC workload.

No records are generated or transformed here. Python repr preserves the input
text, including non-BMP Unicode, when CPython and Pystachy parse the literal.
"""
import argparse
import hashlib
import json
from pathlib import Path


def digest(data):
    return hashlib.sha256(data).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--small", required=True, type=Path)
    parser.add_argument("--full", required=True, type=Path)
    parser.add_argument("--out-dir", required=True, type=Path)
    args = parser.parse_args()
    output = args.out_dir.resolve()
    module = output / "gc_json_fixture.py"
    manifest_path = output / "gc_json_fixture.manifest.json"
    if module.exists() or manifest_path.exists():
        parser.error("use a fresh output directory; fixture files already exist")
    sources, rows = {}, {}
    for name, path in (("SMALL", args.small), ("FULL", args.full)):
        data = path.read_bytes()
        text = data.decode("utf-8")
        value = json.loads(text)
        if not isinstance(value, list) or not value:
            parser.error(f"{name} must contain a nonempty JSON array")
        rows[name] = {"path": str(path.resolve()), "sha256": digest(data),
                      "bytes": len(data), "records": len(value)}
        sources[name] = text
    code = '# Generated by bench/gc_application/embed_fixture.py; exact prepared JSON text.\n'
    for name in ("SMALL", "FULL"):
        code += name + ": str = " + repr(sources[name]) + "\n"
    data = code.encode("utf-8")
    manifest = {"schema_version": 1, "inputs": rows,
                "generator_sha256": digest(Path(__file__).read_bytes()),
                "module_sha256": digest(data), "module_bytes": len(data),
                "note": "Distinct workload: static literal input removes managed input allocation and file I/O."}
    output.mkdir(parents=True, exist_ok=True)
    module.write_bytes(data)
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
