# pow(a, b, m) with a negative b is the power of a's inverse modulo m (Python 3.8+), and m's sign is the result's
cases = [(3, -1, 7), (3, -2, 7), (-3, -1, 7), (3, -1, -7), (2, -1, 1), (2, -1, -1), (5, 0, -7), (5, 0, 1), (0, 0, 5),
         (10, -1, 17), (123456789, -1, 1000000007), (-9223372036854775808, -1, 9223372036854775807),
         (9223372036854775807, -3, -9223372036854775808 + 1), (7, -9223372036854775808, 13), (6, 5, -9223372036854775808),
         (-9223372036854775808, 2, -1), (2, 62, 9223372036854775807), (3, -1, 9223372036854775807)]
for c in cases:
    print(c, pow(c[0], c[1], c[2]))
print(pow(2, -1, 4))
