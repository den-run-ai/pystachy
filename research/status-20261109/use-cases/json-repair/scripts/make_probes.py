"""Write replay-format probe inputs (id, api, input, flags) for differential checks."""
import json, sys
P = []
def add(tag, text, api="repair_json", **flags):
    if api == "repair_json":
        flags.setdefault("return_objects", True)
    P.append({"id": 10000 + len(P), "api": api, "input": text, "flags": flags, "tag": tag})

# Upstream bugs fixed after 0.64.1 (issue numbers in mangiucugna/json_repair)
add("u240", '{"a": /* comment */ 1}')
add("u240", '{"a": // note\n "x", "b": 2}')
add("u240", '{"a": /* c */ {"b": 1}}')
add("u240", '{"a": # c\n true}')
add("u240-1074", '{"a" /* note */: 1}', api="loads")
add("u240-1074", '{"a" /* note */: 1}', api="loads", strict=True)
add("u240", '[1, /* comment */]')
add("u246", '{"a":0,"a":1}', api="loads", strict=True)
add("u246", '{"a":0,"a":1}', api="loads", strict=True, skip_json_loads=True)
add("u247", '{"path": "C:\\\\"')
add("u247", '["R\\\\"]', skip_json_loads=True)
add("u249", '{}, {"id": 1}')
add("u249", '[1], []')
add("u250", '{"a": 1,, "b": 2}', api="loads")
add("u250", '{"a": 1,,2}', api="loads")
add("u250", '{"a": 1,, "b": 2}', api="loads", strict=True)
add("u251", '{"n": 1e+}')
add("u251", '[1e, 2]')
add("u251", '[1e+, 2]')
add("cb5b80e", '""', return_objects=False)
add("cb5b80e", '""', logging=True)
# Port-documented heuristics and port-only behavior
add("slash", '[/1,2]')
add("slash", '[/abc]')
add("slash", '{"k":/42}')
add("slash", '{"k":/ /*x*/true}')
add("comment-unclosed", '{/* unclosed }', api="loads", strict=True)
for c in ['/* note */', '// note\n', '# note\n']:
    add("comment-boundary", '{' + c + ' "a" ' + c + ': 1 ' + c + ', ' + c + ' "b": 2 ' + c + '}', api="loads", logging=True)
    add("comment-boundary", '{' + c + ' "a" ' + c + ': 1 ' + c + ', ' + c + ' "b": 2 ' + c + '}', api="loads", strict=True)
add("heur-fal", '[fal')
add("heur-fal", '{"a": fal')
add("heur-repeat", '{"a":1}{"a":2}')
add("heur-repeat", '{"a":1}{"b":2}')
add("heur-emoji", '{"a": "\\ud83d\\ude00}')
add("heur-emoji", '{"a": "x\\ud83d\\ude00y"')
add("heur-emoji-valid", '{"a": "\\ud83d\\ude00"}')
add("prim-root", '42', skip_json_loads=True)
add("prim-root", '"x"', skip_json_loads=True)
add("prim-root", 'true', skip_json_loads=True)
add("prim-root", '12345678901234567890', skip_json_loads=True)
add("prim-prose", '/* c */ 42')
add("prim-prose", 'The answer is 42')
add("prim-prose", '42 // c')
add("unicode", '[é]', api="loads")
add("unicode", '{界:1}', api="loads")
add("unicode-strict", '{é:, 界:2}', api="loads", strict=True)
add("unicode-strict", '"界":1}', api="loads", strict=True)
add("unicode-strict", '{é:1}{界:2}', api="loads", strict=True)
add("wide", '{"a": 123456789012345678901234567890,}')
add("wide", '[18446744073709551616, -9223372036854775809]')
with open(sys.argv[1], "w") as out:
    for row in P:
        out.write(json.dumps({k: row[k] for k in ("id", "api", "input", "flags")}, ensure_ascii=True) + "\n")
with open(sys.argv[2], "w") as out:
    json.dump({str(r["id"]): r for r in P}, out, ensure_ascii=True, indent=1)
print(len(P), "probes")
