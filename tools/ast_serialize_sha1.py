"""Write lib/ast_serialize/_sha1.py: SHA-1 (FIPS 180-4) with its 80 rounds written out.

The parser's source hash is a SHA-1 of every file it reads. A loop over the rounds keeps the
message schedule in a list; written out, the schedule is sixteen locals and a block reads no
list, which runs about a quarter fewer instructions when compiled; a block's last byte is read
first, which leaves the other 63 reads without a bounds check. With --check, the tool
fails if the file differs from what it writes, and compares the function with hashlib.
Usage: python3 -I tools/ast_serialize_sha1.py [--check]
"""
import hashlib
import importlib.util
from pathlib import Path
import random
import sys

OUT = Path(__file__).resolve().parent.parent / "lib" / "ast_serialize" / "_sha1.py"
ROUNDS = (("(({b} & {c}) | (({b} ^ 0xFFFFFFFF) & {d}))", "0x5A827999"), ("({b} ^ {c} ^ {d})", "0x6ED9EBA1"),
          ("(({b} & {c}) | ({b} & {d}) | ({c} & {d}))", "0x8F1BBCDC"), ("({b} ^ {c} ^ {d})", "0xCA62C1D6"))
HEAD = '''"""SHA-1 (FIPS 180-4) of bytes, as a lowercase hex digest: the source hash ast_serialize returns
(Pystachy has no hashlib). The 80 rounds are written out, with the message schedule in sixteen
locals, so that a block reads no list. Generated by tools/ast_serialize_sha1.py: edit that."""

_HEX = "0123456789abcdef"


def _block(m: bytes, off: int, h: list[int]) -> None:
    # the 64-byte block of m at off, into the state h. An offset is below 2**62, and the block's
    # last byte is read first: the compiler then sees that no index below can overflow or pass
    # the end, and reads the words four bytes at a time with no check
    off &= 0x3FFFFFFFFFFFFFFF
    last = m[off + 63]
'''
TAIL = '''

def sha1_hex(data: bytes) -> str:
    h = [0x67452301, 0xEFCDAB89, 0x98BADCFE, 0x10325476, 0xC3D2E1F0]
    n = len(data)
    full = n - n % 64
    for off in range(0, full, 64):
        _block(data, off, h)
    # the rest of the data, a 0x80 byte, zeros, and the length in bits as eight bytes
    tail_len = 64 - (n - full + 9) % 64
    if tail_len == 64:
        tail_len = 0
    bit_len = n * 8
    length = [0] * 8
    for i in range(8):
        length[7 - i] = (bit_len >> (8 * i)) & 0xFF
    tail = data[full:] + b"\\x80" + bytes(tail_len) + bytes(length)
    for off in range(0, len(tail), 64):
        _block(tail, off, h)
    out: list[str] = []
    for v in h:
        for k in range(28, -4, -4):
            out.append(_HEX[(v >> k) & 15])
    return "".join(out)
'''


def generate():
    lines = []
    for i in range(16):
        low = "last" if i == 15 else f"m[off + {4 * i + 3}]"
        lines.append(f"    w{i} = (m[off + {4 * i}] << 24) | (m[off + {4 * i + 1}] << 16) | (m[off + {4 * i + 2}] << 8) | {low}")
    names = ["a", "b", "c", "d", "e"]
    lines += [f"    {name} = h[{i}]" for i, name in enumerate(names)]
    for r in range(80):
        a, b, c, d, e = names
        w = f"w{r % 16}"
        if r >= 16:
            lines.append(f"    x = w{(r - 3) % 16} ^ w{(r - 8) % 16} ^ w{(r - 14) % 16} ^ {w}")
            lines.append(f"    {w} = ((x << 1) | (x >> 31)) & 0xFFFFFFFF")
        f, k = ROUNDS[r // 20]
        f = f.format(b=b, c=c, d=d)
        lines.append(f"    {e} = (((({a} << 5) | ({a} >> 27)) & 0xFFFFFFFF) + {f} + {e} + {k} + {w}) & 0xFFFFFFFF")
        lines.append(f"    {b} = (({b} << 30) | ({b} >> 2)) & 0xFFFFFFFF")
        names = [e, a, b, c, d]
    lines += [f"    h[{i}] = (h[{i}] + {name}) & 0xFFFFFFFF" for i, name in enumerate(names)]
    return HEAD + "\n".join(lines) + "\n" + TAIL


def compare():
    spec = importlib.util.spec_from_file_location("pystachy_ast_serialize_sha1", OUT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    rng = random.Random(1)
    for n in list(range(0, 260)) + [1000, 4095, 4096, 65543]:
        data = bytes(rng.randrange(256) for _ in range(n))
        if module.sha1_hex(data) != hashlib.sha1(data).hexdigest():
            sys.exit(f"ast_serialize_sha1: sha1_hex differs from hashlib for {n} bytes")


def main():
    text = generate()
    if sys.argv[1:] == ["--check"]:
        if OUT.read_text() != text:
            sys.exit(f"ast_serialize_sha1: {OUT} is not what this tool writes")
        sys.dont_write_bytecode = True  # (no __pycache__ in lib/)
        compare()
        print("ast_serialize_sha1: the file is current and agrees with hashlib")
    elif sys.argv[1:]:
        sys.exit(__doc__)
    else:
        OUT.write_text(text)


if __name__ == "__main__":
    main()
