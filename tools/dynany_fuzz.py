"""Differential fuzzing of dynamic Any (#802).

Seeded programs that opt in to dynamic Any (docs/dynamic-any.md) apply operators, comparisons,
membership, identity, truth, indexing, slicing, formatting and builtins to a pool of Any values:
ints at the small-int cache's and 64-bit boundaries, floats (-0.0, inf, NaN), bools, None, strs,
lists, tuples, dicts and objects of classes whose dunders are defined, missing, reflected,
inherited from a base, overridden by a subclass or asymmetric. Each case prints its result's repr,
or the exception it raised, as CPython does. CPython runs each program, then Pystachy (`run`, the
JIT; with --aot also `build`), which must print the same lines and exit status, but where a
documented deviation or a tracked bug applies: EXPECTED holds a narrow rule for each, which names
its test or issue, and only shrinks.

After each case, the program checks invariants that CPython guarantees on the result and the left
operand, and prints a line only where one fails: `a is b` exactly where `id(a) == id(b)` (#797);
`x in [y]` exactly where `y is x or y == x`, as CPython's list_contains() compares the stored item
with the probe after an identity check (an asymmetric __eq__ tells these apart from x == y); and
equal values of builtin types hash alike. Classes whose __eq__ obeys no law (Yes, No) take part in
the first two only.

Deterministic: each program comes from random.Random(SEED). A mismatch prints the seed, the case,
its expression and both outputs; --keep DIR keeps the programs, and --emit SEED prints one.
Each program also compares concretely annotated and Any functions directly, including side-effect
traces and the first exception. These parity cases have no expected-difference exemptions.
--gc-stress repeats the selected modes with a collection at every program allocation, without
stressing the compiler. AOT binaries are built once and executed in both configurations.

usage: python3 tools/dynany_fuzz.py [--aot] [--gc-stress] [--keep DIR] [--compiler CMD] [SEEDS [N]]
       python3 tools/dynany_fuzz.py --emit SEED [N]
       (SEEDS programs, seeds 1 to SEEDS, of N random + 30 parity cases: default 3 and 150)
"""
import os
import random
import re
import shlex
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# CPython, as the programs run in it: isolated, and without the DeprecationWarning of ~ of a bool,
# which Pystachy does not give (tests/programs/upstream/upstream_bool.py), for the same result;
# and with no cap on the digits of an int it prints, so that an int past 64 bits shows as one
# (big_int()), not as the ValueError of a conversion past 4,300 digits
CPYTHON = [sys.executable, "-I", "-X", "int_max_str_digits=0", "-W", "ignore:Bitwise inversion:DeprecationWarning"]

# The value pool: (source of the value, kind). A kind tells the generator what an operand is,
# for the cases it leaves out (see allowed()).
POOL: list[tuple[str, str]] = [
    ("0", "int"), ("1", "int"), ("-1", "int"), ("2", "int"), ("7", "int"), ("-3", "int"),
    ("-5", "int"), ("-6", "int"), ("255", "int"), ("256", "int"), ("257", "int"),
    ("1000", "int"), ("-1000", "int"), ("9223372036854775807", "bigint"),
    ("-9223372036854775808", "bigint"), ("int('1000')", "int"),
    ("0.0", "float"), ("-0.0", "float"), ("1.5", "float"), ("-2.25", "float"), ("1e300", "float"),
    ("float('inf')", "float"), ("float('nan')", "float"),
    ("True", "bool"), ("False", "bool"), ("None", "none"),
    ("''", "str"), ("'a'", "str"), ("'ab'", "str"), ("'b'", "str"), ("'10'", "str"),
    ("[]", "list"), ("[1]", "list"), ("[1, 'a']", "list"), ("[Num(1), 2]", "list"),
    ("()", "tuple"), ("(1,)", "tuple"), ("(1, 2.5)", "tuple"), ("('a', None)", "tuple"),
    ("{}", "dict"), ("{'k': 1}", "dict"), ("{1: 'x', 2.5: None}", "dict"),
    ("Plain()", "plain"), ("Num(3)", "obj"), ("Num(-1)", "obj"), ("Big(4)", "obj"),
    ("Yes()", "lawless"), ("No()", "lawless"),
]
BINARY = ["+", "-", "*", "/", "//", "%", "**", "<<", ">>", "&", "|", "^",
          "==", "!=", "<", "<=", ">", ">=", "in", "not in", "is", "is not"]
UNARY = ["-{}", "+{}", "~{}", "not {}", "bool({})", "len({})", "str({})", "repr({})", "int({})",
         "float({})", "hash({})", "f'{{{}}}'", "format({}, '')", "{}[0]", "{}[-1]", "{}[1:]",
         "list({})", "sorted({})", "min({})", "max({})", "sum({})"]

PRELUDE = '''# pystachy: dynamic-any
# Generated by tools/dynany_fuzz.py (seed SEED, N cases): run it under CPython and Pystachy and
# compare the outputs.
from typing import Any


class Plain:
    pass


class Num:
    def __init__(self, v: int) -> None:
        self.v = v

    def __repr__(self) -> str:
        return "Num(" + str(self.v) + ")"

    def __eq__(self, o: Any) -> bool:
        return isinstance(o, Num) and self.v == o.v

    def __hash__(self) -> int:
        return self.v

    def __lt__(self, o: Any) -> bool:
        return isinstance(o, Num) and self.v < o.v

    def __add__(self, o: Any) -> Any:
        return Num(self.v + 1)

    def __radd__(self, o: Any) -> Any:
        return Num(self.v + 100)

    def __mul__(self, o: Any) -> Any:
        return Num(self.v * 2)

    def __neg__(self) -> Any:
        return Num(-self.v)

    def __bool__(self) -> bool:
        return self.v != 0


class Big(Num):
    def __radd__(self, o: Any) -> Any:
        return Num(self.v + 1000)


class Yes:
    def __repr__(self) -> str:
        return "Yes()"

    def __eq__(self, o: Any) -> bool:
        return True

    def __hash__(self) -> int:
        return 1


class No:
    def __repr__(self) -> str:
        return "No()"

    def __eq__(self, o: Any) -> bool:
        return False

    def __hash__(self) -> int:
        return 2


def show(k: int, r: Any) -> None:
    print(k, repr(r))


def fail(k: int, e: Exception) -> None:
    print(k, type(e).__name__ + ":", e)


def builtin_value(x: Any) -> bool:
    return x is None or isinstance(x, int) or isinstance(x, float) or isinstance(x, str) or isinstance(x, tuple)


def inv(k: int, a: Any, b: Any) -> None:
    # (a is the result, b the left operand: both alive)
    if (a is b) != (id(a) == id(b)):
        print(k, "INVARIANT: is and id() disagree")
    if (a in [b]) != (b is a or b == a):
        print(k, "INVARIANT: x in [y] is not y is x or y == x")
    if builtin_value(a) and builtin_value(b) and a == b:
        try:
            if hash(a) != hash(b):
                print(k, "INVARIANT: equal values hash apart")
        except TypeError:
            pass


'''


def allowed(op: str, a: str, b: str) -> bool:
    # cases left out: a Plain object's repr (its address) shown, or one as a dict key (KeyError's
    # message shows it); a sequence repeated, a power taken or a shift made so large that CPython
    # would take long or run out of memory; hash() where CPython's varies from run to run (strs,
    # a NaN) or runs the program's __hash__
    va, ka = a
    vb, kb = b
    seq = ("str", "list", "tuple")
    if op in ("str({})", "repr({})", "f'{{{}}}'", "format({}, '')", "list({})", "sorted({})", "min({})", "max({})") and ka in ("plain",):
        return False
    if op == "hash({})" and (ka not in ("int", "bigint", "float", "bool", "none") or va == "float('nan')"):
        return False  # (a NaN's hash is its object's in CPython 3.13)
    if op == "[]" and kb == "plain":
        return False
    if op == "*" and ((ka in seq and kb in ("bigint",)) or (kb in seq and ka in ("bigint",))):
        return False
    if op == "**" and kb in ("bigint",) and ka in ("int", "bigint", "bool"):
        return False
    if op == "<<" and kb in ("bigint",):
        return False
    return True


def parity_program(seed: int, start: int) -> tuple[str, list[tuple[str, str, str, str, str]]]:
    # Each pair differs only in its parameter annotations and the helper's return annotation.
    # Arguments are made afresh for each call, so mutations cannot mask a difference.
    v = random.Random(seed).randrange(2, 20)
    recipes = [
        ("int", "int", str(v), "3", "a + b"),
        ("int", "int", str(-v), "3", "a // b"),
        ("int", "int", str(-v), "3", "a % b"),
        ("int", "int", str(v), "0", "a / b"),
        ("int", "int", str(v), "2", "a ** b"),
        ("float", "float", "1.5", "-2.25", "a + b"),
        ("float", "float", "-0.0", "2.0", "a * b"),
        ("str", "str", "'ab'", "'cd'", "a + b"),
        ("str", "str", "'ab'", "'cd'", "a < b"),
        ("str", "int", "'abc'", "-1", "a[b]"),
        ("str", "int", "'abc'", "8", "a[b]"),
        ("list[int]", "list[int]", f"[{v}, 1]", f"[{v}, 1]", "a == b"),
        ("list[int]", "list[int]", f"[{v}]", "[1, 2]", "a + b"),
        ("list[int]", "int", f"[{v}, 1]", "-1", "a[b]"),
        ("dict[str, int]", "str", f"{{'k': {v}}}", "'k'", "a[b]"),
        ("dict[str, int]", "str", f"{{'k': {v}}}", "'missing'", "a[b]"),
        ("dict[str, int]", "dict[str, int]", f"{{'k': {v}}}", "{'k': 2, 'x': 3}", "a | b"),
        ("tuple[int, int]", "tuple[int, int]", f"({v}, 1)", f"({v}, 1)", "a == b"),
        ("Num", "Num", f"Num({v})", f"Num({v})", "a == b"),
        ("Num", "Num", f"Num({v})", f"Num({v})", "a != b"),
        ("Num", "Num", f"Num({v})", f"Num({v + 1})", "a < b"),
        ("Num", "Num", f"Num({v})", f"Num({v})", "hash(a) == hash(b)"),
        ("int", "list[int]", str(v), f"[1, {v}]", "a in b"),
        ("Num", "list[Num]", f"Num({v})", f"[Num(1), Num({v})]", "a in b"),
    ]
    # Traces expose evaluation order even when the computed result is commutative.
    # first-error verifies that the second argument is not touched after the first raises.
    events = [
        (str(v), "3", "mark(a, 1, trace) + mark(b, 2, trace)"),
        (str(v), "3", "mark(a, 1, trace) - mark(b, 2, trace)"),
        ("0", "3", "mark(a, 1, trace) and mark(b, 2, trace)"),
        ("1", "3", "mark(a, 1, trace) or mark(b, 2, trace)"),
        (str(v), "3", "pair(mark(a, 1, trace), mark(b, 2, trace))"),
        (str(v), "3", "pair(mark(a, -1, trace), mark(b, 2, trace))"),
    ]
    recipes += [("int", "int", a, b, expr) for a, b, expr in events]
    out = ["def parity_pair(a: int, b: int) -> int:", "    return a * 10 + b", ""]
    for mode, typ in (("typed", "int"), ("any", "Any")):
        out += [f"def parity_mark_{mode}(x: {typ}, label: int, trace: list[int]) -> {typ}:",
                "    trace.append(label)", "    if label < 0:", "        raise ValueError('first')",
                "    return x", ""]
    cases = []
    for i, (at, bt, a, b, expr) in enumerate(recipes):
        k = start + i
        for mode in ("typed", "any"):
            atype, btype = (at, bt) if mode == "typed" else ("Any", "Any")
            expression = expr.replace("mark(", f"parity_mark_{mode}(").replace("pair(", "parity_pair(")
            out += [f"def parity_{mode}_{i}(a: {atype}, b: {btype}) -> str:",
                    "    trace: list[int] = []", "    try:", f"        result = repr({expression})",
                    "    except Exception as e:", "        result = type(e).__name__ + ': ' + str(e)",
                    "    return result + ' trace=' + repr(trace)", ""]
        out += [f"pt{k} = parity_typed_{i}({a}, {b})", f"pa{k} = parity_any_{i}({a}, {b})",
                f"show({k}, pt{k})", f"if pt{k} != pa{k}:",
                f"    print({k}, 'INVARIANT: typed/Any parity:', pa{k})", ""]
        cases.append((expr, "parity", at, a, ""))
    return "\n".join(out), cases


def program(seed: int, n: int) -> tuple[str, list[tuple[str, str, str, str, str]]]:
    # the source of program SEED, and its cases: (expression, operator, left operand's kind, its
    # source, its variable)
    rnd = random.Random(seed)
    out = [PRELUDE.replace("SEED", str(seed)).replace("N cases", f"{n} random + 30 parity cases")]
    names: list[tuple[str, str]] = []
    for i, (src, kind) in enumerate(POOL):
        out.append(f"v{i}: Any = {src}")
        names.append((f"v{i}", kind))
    out.append("")
    cases: list[tuple[str, str, str, str, str]] = []
    while len(cases) < n:
        x = rnd.random()
        if x < 0.15:
            # in place, on a new value made from the pool's source, so that no case changes the
            # pool's lists and dicts for the cases after it
            i, j = rnd.randrange(len(POOL)), rnd.randrange(len(POOL))
            op = rnd.choice(BINARY[:12])
            if not allowed(op, POOL[i], POOL[j]):
                continue
            cases.append((f"{POOL[i][0]} {op}= {names[j][0]}", op + "=", POOL[i][1], POOL[i][0], names[i][0]))
        elif x < 0.75:
            i, j = rnd.randrange(len(POOL)), rnd.randrange(len(POOL))
            op = rnd.choice(BINARY + ["[]"])
            if not allowed(op, POOL[i], POOL[j]):
                continue
            expr = f"{names[i][0]}[{names[j][0]}]" if op == "[]" else f"{names[i][0]} {op} {names[j][0]}"
            cases.append((expr, op, POOL[i][1], POOL[i][0], names[i][0]))
        else:
            i = rnd.randrange(len(POOL))
            op = rnd.choice(UNARY)
            if not allowed(op, POOL[i], ("", "")):
                continue
            cases.append((op.format(names[i][0]), op, POOL[i][1], POOL[i][0], names[i][0]))
    for k, (expr, op, kind, src, left) in enumerate(cases):
        out.append("try:")
        if op.endswith("=") and op not in ("==", "!=", "<=", ">="):
            # (the invariants compare the result with the left operand as it was: the same list
            # after +=, a new int after +=)
            out.append(f"    r{k}: Any = {src}")
            out.append(f"    l{k}: Any = r{k}")
            out.append(f"    r{k} {op} {expr.split(' ')[-1]}")
            left = f"l{k}"
        else:
            out.append(f"    r{k}: Any = {expr}")
        out.append(f"    show({k}, r{k})")
        out.append(f"    inv({k}, r{k}, {left})")
        out.append("except Exception as e:")
        out.append(f"    fail({k}, e)")
    parity, pairs = parity_program(seed, len(cases))
    out += ["", parity]
    cases += pairs
    return "\n".join(out), cases


def big_int(line: str) -> bool:
    # does CPython's line show an int that 64 bits do not hold (one of more than 19 digits does,
    # which int() would not read past 4,300)
    m = re.fullmatch(r"\d+ (-?)(\d+)", line)
    return m is not None and (len(m.group(2)) > 19 or not -(2 ** 63) <= int(m.group(1) + m.group(2)) < 2 ** 63)


def type_name(src: str, kind: str) -> str:
    # the name of the type of the pool's value SRC, of KIND, as CPython's messages show it
    if kind in ("plain", "obj", "lawless"):
        return src.split("(")[0]
    return {"bigint": "int", "none": "NoneType"}.get(kind, kind)


def right_type(c: tuple[str, str, str, str, str]) -> str:
    # the type name of a binary or in-place case's right operand: the pool's value v<j> its
    # expression ends with
    return type_name(*POOL[int(c[0].split(" ")[-1][1:])])


# Expected differences: (rule, reason). A rule takes the case and both lines (CPython's, then
# Pystachy's) and says whether the difference is this one.
EXPECTED = [
    (lambda c, cp, ps: big_int(cp) and ps.split(" ")[1:2] == ["OverflowError:"],
     "ints hold 64 bits: OverflowError where CPython's int grows (docs/language/compatibility.md)"),
    (lambda c, cp, ps: c[1] in ("%", "%=") and c[2] == "str"
     and re.fullmatch(r"\d+ " + re.escape(f"TypeError: unsupported operand type(s) for {c[1]}: 'str' and '{right_type(c)}'"), ps) is not None,
     "% of an Any str: this TypeError, where CPython formats or raises its own (tests/deviations/dynany_str_mod.py)"),
    (lambda c, cp, ps: c[1] in ("**", "**=") and re.fullmatch(r"\d+ \(?[-+0-9.einfa]*j\)?", cp) is not None
     and ps.split(" ", 1)[1:] == ["ValueError: a negative number to a fractional power has a complex result (not supported)"],
     "no complex numbers (tests/deviations/complex_pow.py)"),
]


def built(seed: int, r: tuple[int, str]) -> list[str]:
    # a build that succeeds prints nothing: what one prints (a warning, a sanitizer's report) is a
    # mismatch, as compare() makes a line of no case one (a failed build: compare() reports it)
    return [f"seed {seed} aot: the build printed: {r[1][-800:]}"] if r[0] == 0 and r[1] != "" else []


def run(cmd: list[str], cwd: str, stress: bool = False, native_program: bool = False) -> tuple[int, str]:
    env = dict(os.environ)
    # Explicitly choose the program configuration; caller stress must not replace the normal run.
    env.pop("PYSTACHY_GC_STRESS", None)
    env.pop("PYSTACHY_GC", None)
    env["PYSTACHY_GC_STRESS_PROGRAM"] = "1" if stress else "0"
    # The driver translates *_PROGRAM for JIT children. A standalone AOT executable reads
    # the runtime's GC_STRESS directly; setting only *_PROGRAM would leave it unstressed.
    if native_program and stress:
        env["PYSTACHY_GC_STRESS"] = "1"
    p = subprocess.run(cmd, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL,
                       text=True, errors="replace", timeout=600, env=env)
    return p.returncode, p.stdout


def by_case(out: str) -> tuple[dict[int, list[str]], list[str]]:
    # the lines of each case, by its number, and the lines that name no case, which compare()
    # requires to be alike too (a warning or a sanitizer's report fails the comparison)
    r: dict[int, list[str]] = {}
    other: list[str] = []
    for line in out.splitlines():
        head = line.split(" ", 1)[0]
        if head.isdigit():
            r.setdefault(int(head), []).append(line)
        else:
            other.append(line)
    return r, other


def case_order(out: str) -> list[int]:
    # the case numbers of out's lines, in the order the program printed them
    return [int(h) for h in (line.split(" ", 1)[0] for line in out.splitlines()) if h.isdigit()]


def compare(seed: int, cases: list[tuple[str, str, str, str, str]], mode: str, cp: tuple[int, str], ps: tuple[int, str]) -> list[str]:
    # the mismatches of Pystachy's output (mode) with CPython's, each a report line
    bad: list[str] = []
    if cp[0] != 0:
        return [f"seed {seed}: CPython exited {cp[0]}: {cp[1][-500:]}"]
    if ps[0] != 0:
        bad.append(f"seed {seed} {mode}: exit status {ps[0]}, CPython's 0: {ps[1][-800:]}")
    a, ao = by_case(cp[1])
    b, bo = by_case(ps[1])
    if ao or sorted(a) != list(range(len(cases))) or any(len(lines) != 1 for lines in a.values()):
        return [f"seed {seed}: CPython did not produce exactly one result for every case"]
    if ao != bo:
        bad.append(f"seed {seed} {mode}: lines of no case differ\n    CPython:  {' | '.join(ao)}\n    Pystachy: {' | '.join(bo)}")
    oa = case_order(cp[1])
    ob = case_order(ps[1])
    if oa != ob and sorted(oa) == sorted(ob):
        # (the same lines in another order: lines that differ are reported below, case by case)
        bad.append(f"seed {seed} {mode}: the cases' lines come in another order than CPython's")
    for k in sorted(set(range(len(cases))) | set(a) | set(b)):
        x = a.get(k, [])
        y = b.get(k, [])
        if x == y:
            continue
        c = cases[k] if k < len(cases) else ("(no such case)", "", "", "", "")
        if k < len(cases) and c[1] != "parity" and len(x) == 1 and len(y) == 1 and any(rule(c, x[0], y[0]) for rule, _ in EXPECTED):
            continue
        bad.append(f"seed {seed} {mode} case {k}: {c[0]}  (v = {c[3]})\n    CPython:  {' | '.join(x)}\n    Pystachy: {' | '.join(y)}")
    return bad


def compiler_cmd(compiler: str) -> list[str]:
    # the words of --compiler's CMD, split as a shell does, each that names a file made absolute, as
    # the programs run in another directory ("python3 pystachy.py": the hosted compiler)
    return [os.path.abspath(w) if os.path.exists(w) else w for w in shlex.split(compiler)]


def main() -> int:
    args = sys.argv[1:]
    aot = "--aot" in args
    gc_stress = "--gc-stress" in args
    keep = ""
    compiler = os.path.join(ROOT, "pystachy")
    rest: list[str] = []
    i = 0
    while i < len(args):
        if args[i] in ("--aot", "--gc-stress"):
            pass
        elif args[i] == "--keep":
            i += 1
            keep = args[i]
        elif args[i] == "--compiler":
            i += 1
            compiler = args[i]
        elif args[i] == "--emit":
            seed = int(args[i + 1])
            n = int(args[i + 2]) if len(args) > i + 2 else 150
            sys.stdout.write(program(seed, n)[0])
            return 0
        else:
            rest.append(args[i])
        i += 1
    seeds = int(rest[0]) if len(rest) > 0 else 3
    n = int(rest[1]) if len(rest) > 1 else 150
    if seeds < 1 or n < 1:
        print("seeds and cases must be positive", file=sys.stderr)
        return 2
    if sys.version_info[:2] != (3, 13):
        print(f"tools/dynany_fuzz.py: CPython {sys.version.split()[0]} runs it; the expected outputs are 3.13's (.python-version)", file=sys.stderr)
        return 2
    work = os.path.abspath(keep) if keep != "" else tempfile.mkdtemp(prefix="pystachy-dynany-fuzz.")
    os.makedirs(work, exist_ok=True)
    cmd = compiler_cmd(compiler)
    bad: list[str] = []
    total = 0
    parity_total = 0
    for seed in range(1, seeds + 1):
        src, cases = program(seed, n)
        total += len(cases)
        parity_total += sum(c[1] == "parity" for c in cases)
        path = os.path.join(work, f"dynany_fuzz_{seed}.py")
        with open(path, "w") as f:
            f.write(src)
        cp = run(CPYTHON + [path], work)
        bad += compare(seed, cases, "jit", cp, run(cmd + ["run", path], work))
        if gc_stress:
            bad += compare(seed, cases, "jit-gc", cp, run(cmd + ["run", path], work, stress=True))
        if aot:
            exe = os.path.join(work, f"dynany_fuzz_{seed}")
            r = run(cmd + ["build", path, "-o", exe], work)
            bad += built(seed, r) + compare(seed, cases, "aot", cp, run([exe], work, native_program=True) if r[0] == 0 else r)
            if gc_stress:
                bad += compare(seed, cases, "aot-gc", cp, run([exe], work, stress=True, native_program=True) if r[0] == 0 else r)
    for line in bad:
        print(line)
    if keep == "":
        for f in os.listdir(work):
            os.unlink(os.path.join(work, f))
        os.rmdir(work)
    modes = ["JIT"] + (["AOT"] if aot else [])
    if gc_stress:
        modes += ["JIT-GC"] + (["AOT-GC"] if aot else [])
    print(f"{seeds} programs, {total} cases, {parity_total} parity cases ({', '.join(modes)}): {len(bad)} mismatches")
    return 1 if bad else 0


