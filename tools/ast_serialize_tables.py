"""Generate the Unicode tables of lib/ast_serialize/: _unicode.py, XID_Start and XID_Continue above
ASCII from a DerivedCoreProperties.txt (17.0.0 for ast-serialize 0.13.1, whose lexer uses the
unicode-ident crate 1.0.22), and _names16.py, the character names and name aliases of a
UnicodeData.txt and NameAliases.txt (16.0.0, unicode_names2 1.3.0's, which the extension's \\N{...}
escapes use) that this CPython's unicodedata.lookup() lacks. Code points are written as base-36
gaps that the modules decode on first use.
Usage: python3 -I tools/ast_serialize_tables.py DerivedCoreProperties.txt UnicodeData.txt
       NameAliases.txt [--check]
"""
import hashlib
from pathlib import Path
import sys

OUT = Path(__file__).resolve().parent.parent / "lib" / "ast_serialize" / "_unicode.py"
NAMES_OUT = OUT.parent / "_names16.py"
DIGITS = "0123456789abcdefghijklmnopqrstuvwxyz"

FUNCTIONS = '''_start: list[int] = []
_continue: list[int] = []


def _decode(text: str, out: list[int]) -> None:
    # out: the first and last code point of each range, in order
    prev = 0x7F
    for pair in text.split(" "):
        dot = pair.find(".")
        first = prev + int(pair[:dot], 36)
        prev = first + int(pair[dot + 1:], 36)
        out.append(first)
        out.append(prev)


def _in(ranges: list[int], cp: int) -> bool:
    lo = 0
    hi = len(ranges) // 2
    while lo < hi:
        mid = (lo + hi) // 2
        if ranges[2 * mid + 1] < cp:
            lo = mid + 1
        else:
            hi = mid
    return lo < len(ranges) // 2 and ranges[2 * lo] <= cp


def is_xid_start(cp: int) -> bool:
    if len(_start) == 0:
        _decode(_START_TEXT, _start)
    return _in(_start, cp)


def is_xid_continue(cp: int) -> bool:
    if len(_continue) == 0:
        _decode(_CONTINUE_TEXT, _continue)
    return _in(_continue, cp)
'''


def properties(text):
    props = {"XID_Start": set(), "XID_Continue": set()}
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        fields = [x.strip() for x in line.split(";")]
        if fields[1] not in props:
            continue
        first, _, last = fields[0].partition("..")
        lo = int(first, 16)
        hi = int(last, 16) if last else lo
        props[fields[1]].update(cp for cp in range(max(lo, 0x80), hi + 1))
    return props


def base36(n):
    s = DIGITS[n % 36]
    while n >= 36:
        n //= 36
        s = DIGITS[n % 36] + s
    return s


def encode(cps):
    ranges = []
    for cp in sorted(cps):
        if ranges and ranges[-1][1] == cp - 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
    parts = []
    prev = 0x7F
    for a, b in ranges:
        parts.append(f"{base36(a - prev)}.{base36(b - a)}")
        prev = b
    lines = []
    text = " ".join(parts)
    while len(text) > 96:
        cut = text.rfind(" ", 0, 96)
        lines.append(text[:cut + 1])
        text = text[cut + 1:]
    lines.append(text)
    return "".join(f'    "{line}"\n' for line in lines)


def generate(path):
    data = Path(path).read_bytes()
    text = data.decode("utf-8")
    version = text.split("\n", 1)[0].removeprefix("# DerivedCoreProperties-").removesuffix(".txt")
    props = properties(text)
    head = (f'"""XID_Start and XID_Continue above ASCII, for the lexer\'s identifiers: Unicode {version}\'s, as the\n'
            "unicode-ident crate (1.0.22) that the extension's lexer uses. Generated by\n"
            f"tools/ast_serialize_tables.py from DerivedCoreProperties-{version}.txt, SHA-256\n"
            f"{hashlib.sha256(data).hexdigest()}. Each \"gap.length\" pair, in\n"
            "base 36, starts a range that many code points past the previous range's end (0x7f first).\n"
            '"""\n\n')
    return (head + "_START_TEXT = (\n" + encode(props["XID_Start"]) + ")\n\n"
            + "_CONTINUE_TEXT = (\n" + encode(props["XID_Continue"]) + ")\n\n" + FUNCTIONS)


NAMES_FUNCTIONS = '''_names: dict[str, int] = {}


def _decode() -> None:
    cp = 0
    for entry in _TEXT.split(";"):
        colon = entry.find(":")
        cp += int(entry[:colon], 36)
        _names[entry[colon + 1:]] = cp


def lookup(name: str) -> int:
    # the code point of an (upper-case) name, -1 for none
    if len(_names) == 0:
        _decode()
    return _names.get(name, -1)
'''


def generate_names(data_path, aliases_path):
    import unicodedata
    data = Path(data_path).read_bytes()
    aliases = Path(aliases_path).read_bytes()
    names = {}
    for line in data.decode("utf-8").splitlines():
        fields = line.split(";")
        cp, name = int(fields[0], 16), fields[1]
        # (the algorithmic EGYPTIAN HIEROGLYPH-XXXX names of 13460..143FA are a rule of _parser.py)
        if name.startswith("<") or (0x13460 <= cp <= 0x143FA and name == f"EGYPTIAN HIEROGLYPH-{cp:X}"):
            continue
        names[name] = cp
    for line in aliases.decode("utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            cp, name, _ = line.split(";")
            names[name] = int(cp, 16)
    new = []
    for name, cp in names.items():
        try:
            unicodedata.lookup(name)
        except KeyError:
            new.append((cp, name))
    new.sort()
    parts = []
    prev = 0
    for cp, name in new:
        parts.append(f"{base36(cp - prev)}:{name}")
        prev = cp
    text = ";".join(parts)
    lines = []
    while len(text) > 96:
        cut = text.rfind(";", 0, 96)
        lines.append(text[:cut + 1])
        text = text[cut + 1:]
    lines.append(text)
    version = data_path.split("/")[-2] if "/" in data_path else "16.0.0"
    head = ('"""The character names and name aliases of the Unicode Character Database 16.0.0 that CPython\n'
            f"{sys.version.split()[0]}'s unicodedata (Unicode {unicodedata.unidata_version}) lacks: unicode_names2 1.3.0, which the\n"
            "extension's \\\\N{...} escapes use, knows them. Generated by tools/ast_serialize_tables.py from\n"
            f"UnicodeData.txt (SHA-256 {hashlib.sha256(data).hexdigest()}) and\n"
            f"NameAliases.txt (SHA-256 {hashlib.sha256(aliases).hexdigest()}): each\n"
            "\"gap:NAME\" entry is a name, its code point that gap (base 36) past the previous one's.\n"
            '"""\n\n')
    del version
    return head + "_TEXT = (\n" + "".join(f'    "{line}"\n' for line in lines) + ")\n\n" + NAMES_FUNCTIONS


def main():
    args = sys.argv[1:]
    check = args[-1:] == ["--check"]
    if check:
        args = args[:-1]
    if len(args) != 3:
        sys.exit(__doc__.strip().split("Usage: ")[-1])
    outputs = [(OUT, generate(args[0])), (NAMES_OUT, generate_names(args[1], args[2]))]
    for out, text in outputs:
        if check:
            if out.read_text() != text:
                sys.exit(f"{out} is not what the Unicode data generates")
            print(f"{out}: up to date")
        else:
            out.write_text(text)
            print(f"wrote {out}")


if __name__ == "__main__":
    main()
