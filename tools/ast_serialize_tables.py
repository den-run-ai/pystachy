"""Generate lib/ast_serialize/_unicode.py: XID_Start and XID_Continue above ASCII, from a Unicode
Character Database DerivedCoreProperties.txt (17.0.0 for ast-serialize 0.13.1, whose lexer uses
the unicode-ident crate 1.0.22). The ranges are written as base-36 "gap.length" pairs that the
module decodes on first use.
Usage: python3 -I tools/ast_serialize_tables.py DerivedCoreProperties.txt [--check]
"""
import hashlib
from pathlib import Path
import sys

OUT = Path(__file__).resolve().parent.parent / "lib" / "ast_serialize" / "_unicode.py"
DIGITS = "0123456789abcdefghijklmnopqrstuvwxyz"

FUNCTIONS = '''_start: list[int] = []
_continue: list[int] = []


def _decode(text: str, out: list[int]) -> None:
    # out: the first and last code point of each range, in order
    prev = 0x7F
    for pair in text.split(" "):
        dot = pair.find(".")
        first = prev + int(pair[:dot], 36)
        prev = first + int(pair[dot + 1:], 36)
        out.append(first)
        out.append(prev)


def _in(ranges: list[int], cp: int) -> bool:
    lo = 0
    hi = len(ranges) // 2
    while lo < hi:
        mid = (lo + hi) // 2
        if ranges[2 * mid + 1] < cp:
            lo = mid + 1
        else:
            hi = mid
    return lo < len(ranges) // 2 and ranges[2 * lo] <= cp


def is_xid_start(cp: int) -> bool:
    if len(_start) == 0:
        _decode(_START_TEXT, _start)
    return _in(_start, cp)


def is_xid_continue(cp: int) -> bool:
    if len(_continue) == 0:
        _decode(_CONTINUE_TEXT, _continue)
    return _in(_continue, cp)
'''


def properties(text):
    props = {"XID_Start": set(), "XID_Continue": set()}
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        fields = [x.strip() for x in line.split(";")]
        if fields[1] not in props:
            continue
        first, _, last = fields[0].partition("..")
        lo = int(first, 16)
        hi = int(last, 16) if last else lo
        props[fields[1]].update(cp for cp in range(max(lo, 0x80), hi + 1))
    return props


def base36(n):
    s = DIGITS[n % 36]
    while n >= 36:
        n //= 36
        s = DIGITS[n % 36] + s
    return s


def encode(cps):
    ranges = []
    for cp in sorted(cps):
        if ranges and ranges[-1][1] == cp - 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
    parts = []
    prev = 0x7F
    for a, b in ranges:
        parts.append(f"{base36(a - prev)}.{base36(b - a)}")
        prev = b
    lines = []
    text = " ".join(parts)
    while len(text) > 96:
        cut = text.rfind(" ", 0, 96)
        lines.append(text[:cut + 1])
        text = text[cut + 1:]
    lines.append(text)
    return "".join(f'    "{line}"\n' for line in lines)


def generate(path):
    data = Path(path).read_bytes()
    text = data.decode("utf-8")
    version = text.split("\n", 1)[0].removeprefix("# DerivedCoreProperties-").removesuffix(".txt")
    props = properties(text)
    head = (f'"""XID_Start and XID_Continue above ASCII, for the lexer\'s identifiers: Unicode {version}\'s, as the\n'
            "unicode-ident crate (1.0.22) that the extension's lexer uses. Generated by\n"
            f"tools/ast_serialize_tables.py from DerivedCoreProperties-{version}.txt, SHA-256\n"
            f"{hashlib.sha256(data).hexdigest()}. Each \"gap.length\" pair, in\n"
            "base 36, starts a range that many code points past the previous range's end (0x7f first).\n"
            '"""\n\n')
    return (head + "_START_TEXT = (\n" + encode(props["XID_Start"]) + ")\n\n"
            + "_CONTINUE_TEXT = (\n" + encode(props["XID_Continue"]) + ")\n\n" + FUNCTIONS)


def main():
    if len(sys.argv) not in (2, 3) or (len(sys.argv) == 3 and sys.argv[2] != "--check"):
        sys.exit(__doc__.strip().split("\n")[-1])
    text = generate(sys.argv[1])
    if len(sys.argv) == 3:
        if OUT.read_text() != text:
            sys.exit(f"{OUT} is not what {sys.argv[1]} generates")
        print(f"{OUT}: up to date")
        return
    OUT.write_text(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
